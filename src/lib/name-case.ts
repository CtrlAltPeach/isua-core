// Нормализация регистра ФИО: «ИВАНОВ оглы АХМЕД» → «Иванов оглы Ахмед».
// Учитывает туркменские/казахские патронимические суффиксы (оглы, кызы, …),
// дефисные имена и апострофы (Иванов-Петров, д'Артаньян).

/**
 * Суффиксы, которые всегда остаются строчными, даже если находятся
 * в середине составного слова (например, «Иванов-ОГЛЫ» → «Иванов-Оглы»
 * не произойдёт — мы ищем их как отдельные части через дефис).
 *
 * Проверка — case-insensitive по суффиксу, результат — строчный.
 */
const PATRONYMIC_SUFFIXES = new Set(["оглы", "кызы", "улы", "сен", "торе", "заде"]);

/**
 * Капитализирует первую букву строки: «abc» → «Abc».
 */
function capitalize(s: string): string {
  if (!s) return s;
  return s[0].toUpperCase() + s.slice(1);
}

/**
 * Обрабатывает одну «часть» имени (слово или фрагмент между дефисами):
 * — если часть совпадает с патронимическим суффиксом — строчная;
 * — иначе: первая буква заглавная, остальные строчные.
 */
function normalizePart(part: string): string {
  if (!part) return part;
  const lower = part.toLowerCase();
  if (PATRONYMIC_SUFFIXES.has(lower)) return lower;
  return capitalize(lower);
}

/**
 * Нормализует полное имя абитуриента по правилам русского регистра.
 *
 * - Схлопывает лишние пробелы и trim.
 * - Каждое слово: первая буква заглавная, остальные строчные.
 * - Дефисные части: каждая капитализируется отдельно (Иванов-Петров).
 * - Патронимические суффиксы (оглы, кызы, улы, и т.д.) — всегда строчные.
 *
 * @example
 * normalizeName("ИВАНОВ ИГОРЬ ПЕТРОВИЧ")   // "Иванов Игорь Петрович"
 * normalizeName("ахмед оглы иванов")         // "Ахмед оглы Иванов"
 * normalizeName("д'АРТАНЬЯН")                // "Д'Артаньян"
 * normalizeName("  ИВАНОВ-ПЕТРОВ  ")         // "Иванов-Петров"
 */
export function normalizeName(raw: string): string {
  if (!raw) return "";
  // trim + схлопнуть несколько пробелов/табов в один.
  const cleaned = raw.trim().replace(/\s+/g, " ");
  if (!cleaned) return "";

  // Разбиваем по пробелам, каждое слово нормализуем.
  return cleaned
    .split(" ")
    .map((word) => {
      // Дефис: каждую часть отдельно.
      if (word.includes("-")) {
        return word.split("-").map(normalizePart).join("-");
      }
      // Апостроф: каждую часть отдельно (д'Артаньян).
      if (word.includes("'")) {
        return word.split("'").map(normalizePart).join("'");
      }
      return normalizePart(word);
    })
    .join(" ");
}
