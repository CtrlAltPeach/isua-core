import { describe, it, expect } from "vitest";
import { normalizeName } from "./name-case";

describe("normalizeName", () => {
  // --- Базовые случаи ---

  it("обычное ФИО с правильным регистром не меняется", () => {
    expect(normalizeName("Иванов Иван Иванович")).toBe("Иванов Иван Иванович");
  });

  it("все заглавные приводятся к стандартному регистру", () => {
    expect(normalizeName("ИВАНОВ ИГОРЬ ПЕТРОВИЧ")).toBe("Иванов Игорь Петрович");
  });

  it("все строчные приводятся к стандартному регистру", () => {
    expect(normalizeName("иванов игорь петрович")).toBe("Иванов Игорь Петрович");
  });

  it("смешанный регистр нормализуется", () => {
    expect(normalizeName("иВАНОВ Иго РЬ")).toBe("Иванов Иго Рь");
  });

  // --- Пробелы и пустые строки ---

  it("лишние пробелы схлопываются", () => {
    expect(normalizeName("  Иванов   Иван  ")).toBe("Иванов Иван");
  });

  it("пустая строка → пустая строка", () => {
    expect(normalizeName("")).toBe("");
  });

  it("только пробелы → пустая строка", () => {
    expect(normalizeName("   ")).toBe("");
  });

  // --- Патронимические суффиксы ---

  it("«оглы» остаётся строчным", () => {
    expect(normalizeName("АХМЕД оглы ИВАНОВ")).toBe("Ахмед оглы Иванов");
  });

  it("«кызы» остаётся строчным", () => {
    expect(normalizeName("МАРИЯ кызы ПЕТРОВА")).toBe("Мария кызы Петрова");
  });

  it("«оглы» в верхнем регистре нормализуется в строчный", () => {
    expect(normalizeName("АХМЕД ОГЛЫ ИВАНОВ")).toBe("Ахмед оглы Иванов");
  });

  it("«кызы» в верхнем регистре нормализуется в строчный", () => {
    expect(normalizeName("МАРИЯ КЫЗЫ ПЕТРОВА")).toBe("Мария кызы Петрова");
  });

  it("«улы» остаётся строчным", () => {
    expect(normalizeName("САБИТ УЛЫ ЖУСУПОВ")).toBe("Сабит улы Жусупов");
  });

  it("«сен» остаётся строчным", () => {
    expect(normalizeName("ОТАР СЕН КЕЛИМБЕТОВ")).toBe("Отар сен Келимбетов");
  });

  it("«торе» остаётся строчным", () => {
    expect(normalizeName("БАТИР ТОРЕ НАЗАРОВ")).toBe("Батир торе Назаров");
  });

  it("«заде» остаётся строчным", () => {
    expect(normalizeName("АЛИ ЗАДЕ ГУСЕЙНОВ")).toBe("Али заде Гусейнов");
  });

  // --- Дефисные фамилии ---

  it("дефис: обе части капитализируются", () => {
    expect(normalizeName("ИВАНОВ-ПЕТРОВ")).toBe("Иванов-Петров");
  });

  it("дефис с суффиксом: первая часть — с заглавной, оглы — строчный", () => {
    expect(normalizeName("АХМЕД-ОГЛЫ")).toBe("Ахмед-оглы");
  });

  it("двойной дефис: все три части капитализируются", () => {
    expect(normalizeName("ИВАНОВ-ПЕТРОВ-СИДОРОВ")).toBe("Иванов-Петров-Сидоров");
  });

  // --- Апострофы ---

  it("апостроф: обе части капитализируются", () => {
    expect(normalizeName("д'АРТАНЬЯН")).toBe("Д'Артаньян");
  });

  it("апостроф в середине ФИО", () => {
    expect(normalizeName("ЖАН д'АЛАМБЕР")).toBe("Жан Д'Аламбер");
  });

  // --- Корнер-кейсы ---

  it("одна буква", () => {
    expect(normalizeName("а")).toBe("А");
  });

  it("одна буква в верхнем регистре", () => {
    expect(normalizeName("Я")).toBe("Я");
  });

  it("имя из одного слова", () => {
    expect(normalizeName("ИВАНОВ")).toBe("Иванов");
  });
});
